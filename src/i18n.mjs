export function createT(lang = "zh") {
  const table = lang === "en" ? en : zh;
  const t = (key, vars = {}) => {
    const template = table[key] ?? zh[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
  };
  t.lang = lang === "en" ? "en" : "zh";
  return t;
}

export function normalizeLang(value) {
  const text = String(value || "").toLowerCase();
  if (text.startsWith("zh") || text === "cn" || text === "中文") return "zh";
  if (text.startsWith("en") || text === "english" || text === "英文") return "en";
  return null;
}

export function resolveLang({ flag, env = process.env, config = {} } = {}) {
  return normalizeLang(flag) || normalizeLang(env.KARMENBOT_LANG) || normalizeLang(config.lang) || "zh";
}
